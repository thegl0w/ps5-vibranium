#!/usr/bin/env python3
"""genstubs.py <d3d12umddi.h> <dxgiddi.h> > stubs.inc
Every entry of the function tables ps5d3d12.dll fills (version 0076) gets a logging stub, so a call we do not handle
yet is named in the log instead of crashing. Stubs carry the entry's own parameter list (32-bit: stdcall, the callee
pops its arguments) and return by the declared type: HRESULT -> E_NOTIMPL, SIZE_T (CalcPrivate*Size) -> 256, else 0.
Emits P5_STUB_TABLE(<table>) arrays of {name, function} in table order; ps5d3d12.cpp copies them into the runtime's
table and then puts the implemented entries over them."""
import re, sys
U = open(sys.argv[1], encoding='latin-1').read()
X = open(sys.argv[2], encoding='latin-1').read()
TABLES = [('core', U, 'D3D12DDI_DEVICE_FUNCS_CORE_0075', r'PFND3D12DDI_\w+'),
          ('list', U, 'D3D12DDI_COMMAND_LIST_FUNCS_3D_0074', r'PFND3D12DDI_\w+'),
          ('queue', U, 'D3D12DDI_COMMAND_QUEUE_FUNCS_CORE_0001', r'PFND3D12DDI_\w+')]
def sig_of(pfn):
    m = re.search(r'typedef\s+(?:_Check_return_\s+)?(\w+\s*\*?)\s*\(\s*APIENTRY\s*(?:CALLBACK\s*)?\*\s*' + pfn + r'\s*\)\s*\((.*?)\)\s*;', U, re.S)
    if not m:
        sys.exit('no typedef for ' + pfn)
    params = re.sub(r'//[^\n]*|/\*.*?\*/', '', m.group(2), flags=re.S)       # comments
    params = ' '.join(params.split())
    params = re.sub(r'\b_(?:In|Out|Inout)\w*_\s*(?:\([^()]*\))?', '', params)   # SAL annotations
    return m.group(1).replace(' ', ''), params
print('// Generated by tools/genstubs.py from the 28000 kit headers; do not edit.')
for tag, src, name, pat in TABLES:
    body = re.search(r'typedef struct ' + name + r'\s*\{(.*?)\}\s*' + name + ';', src, re.S).group(1)
    ents = re.findall(r'(' + pat + r'|void\s*\*)\s+(pfn\w+)\s*;', body)     # void* slots (e.g. the queue's pfnUnused) keep their place
    rows = []
    for i, (pfn, fn) in enumerate(ents):
        if pfn.startswith('void'):
            rows.append('{"%s", NULL}' % fn)
            continue
        r, params = sig_of(pfn)
        if r in ('VOID', 'void'):
            body_ = ''
        else:
            body_ = ' return E_NOTIMPL;' if r == 'HRESULT' else ' return 256;' if r == 'SIZE_T' else ' %s r_ = {}; return r_;' % r
        print('static %s APIENTRY stub_%s_%s(%s) { P5Stub("%s.%s");%s }  // %s' % (r, tag, fn, params, tag, fn, body_, pfn))
        rows.append('{"%s", (void*)stub_%s_%s}' % (fn, tag, fn))
    print('static const P5StubEntry kStubs_%s[] = {\n    %s\n};' % (tag, ',\n    '.join(rows)))
# DXGI table: DXGI1_6_1_DDI_BASE_FUNCTIONS (function pointers declared inline, all HRESULT)
body = re.search(r'typedef struct DXGI1_6_1_DDI_BASE_FUNCTIONS\s*\{(.*?)\}\s*DXGI1_6_1_DDI_BASE_FUNCTIONS;', X, re.S).group(1)
names = re.findall(r'\*\s*(pfn\w+)\s*\)', body)
rows = []
for fn in names:
    print('static HRESULT APIENTRY stub_dxgi_%s(void*) { P5Stub("dxgi.%s"); return E_NOTIMPL; }' % (fn, fn))
    rows.append('{"%s", (void*)stub_dxgi_%s}' % (fn, fn))
print('static const P5StubEntry kStubs_dxgi[] = {\n    %s\n};' % ',\n    '.join(rows))
