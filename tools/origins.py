"""Per-file origin list of the public tree: path, SHA-256, origin, licence, and the clone detector's finding.
Usage: tools/origins.py <export tree> <clonecheck report.md> <out.md>
Origins come from the rules below (one per area, checked against each file's own header) and the clone-detector report."""
import hashlib, re, sys
from pathlib import Path

RULES = [  # (path regex, origin, licence)
    (r"^release/licenses/", "third-party licence text, verbatim", "as named in the file"),
    (r"^(README\.md|release/README\.md)$", "ours", "MIT"),
    (r"^cleanroom/spec-", "clean-room specification (written description; see CLEANROOM.md)", "MIT"),
    (r"^cleanroom/directload-mit/", "clean-room rewrite from cleanroom/spec-directload.md (replaces MetalCyan's CyanDirectLoad)", "MIT"),
    (r"^cleanroom/p5eth-mit/", "clean-room rewrite from cleanroom/spec-p5eth.md (replaces our earlier GPL driver)", "MIT"),
    (r"^cleanroom/ps5reset-mit/", "clean-room rewrite from cleanroom/spec-icc-reset.md (replaces our earlier GPL library)", "MIT"),
    (r"^firmware/kms_linear\.py$", "derived from ps5-hackintosh bringup/tools/kms_linear.py (rodri0x), credited in its header", "MIT"),
    (r"^firmware/windows_kstub.*\.inc$", "generated by firmware/make_kstub.py (our code, offsets, fingerprints)", "MIT"),
    (r"^firmware/windows_kpat\.inc$", "generated by firmware/make_kpat.py", "MIT"),
    (r"^firmware/", "ours (applied to EDK2 / ps5-hackintosh's UEFI build at build time)", "MIT"),
    (r"^ps5gpu/mesa/mesa-ps5\.patch$", "our changes to Mesa 26.3.1", "MIT (Mesa's licence)"),
    (r"^ps5gpu/mesa/", "ours (Mesa build glue / winsys for libps5gpu)", "MIT"),
    (r"^ps5gpu/", "ours (register names from Linux's MIT amdgpu headers, included at build, not copied)", "MIT"),
    (r"^(image|installer|winremote|tools|docs|\.github)/", "ours", "MIT"),
    (r"^ps5wifi/devadd\.c$", "ours (MIT; the only file shipped from the ps5wifi folder)", "MIT"),
    (r"^release/", "ours", "MIT"),
    (r"^(SECURITY|CONTRIBUTING)\.md$|^\.gitignore$", "ours", "MIT"),
    (r"^LICENSE$", "ours (the MIT text of release/LICENSE)", "MIT"),
]
# Not published: the export repo's own git data and OS/editor clutter. Skipped so a run on the git-tracked export
# lists only the shipped tree (the run on 2026-11-23 listed 264 .git/ rows as UNCLASSIFIED).
SKIP_DIRS = {".git", "__pycache__"}
SKIP_FILES = {".DS_Store"}
SELF = {("ps5wifi/devadd.c", "GPL-ps5wifi", "devadd.c")}   # the corpus copy is the same file of ours (MIT), not a source


def main():
    tree, report, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    hits = {}
    for line in report.read_text().splitlines():
        m = re.match(r"\| `([^`]+)` \| ([^|]+) \| `([^`]+)` \| (\d+) \| (\d+) \|", line)
        if m and (m[1], m[2].strip(), m[3]) not in SELF:
            hits.setdefault(m[1], []).append(f"{m[2].strip()}:{m[3]} ({m[4]} runs, longest {m[5]} lines)")
    rows = []
    for p in sorted(x for x in tree.rglob("*") if x.is_file()):
        rel = p.relative_to(tree).as_posix()
        if SKIP_DIRS.intersection(rel.split("/")[:-1]) or p.name in SKIP_FILES:
            continue
        origin, lic = next(((o, l) for rx, o, l in RULES if re.search(rx, rel)), ("UNCLASSIFIED", "?"))
        sha = hashlib.sha256(p.read_bytes()).hexdigest()[:16]
        rows.append(f"| `{rel}` | `{sha}` | {origin} | {lic} | {'; '.join(hits.get(rel, [])) or '-'} |")
    unclassified = sum("UNCLASSIFIED" in r for r in rows)
    text = ["# Per-file origin list", "",
            f"{len(rows)} files. SHA-256 (first 16 hex digits) of the file as published. \"Shared code\" = the clone detector's",
            "finding for that file (`tools/clonecheck.py`; see CLEANROOM.md for how each one is explained).", "",
            "| File | SHA-256 | Origin | Licence | Shared code (clone detector) |", "|---|---|---|---|---|"] + rows
    out.write_text("\n".join(text) + "\n")
    print(f"{len(rows)} files, {unclassified} unclassified, {len(hits)} with shared code")


if __name__ == "__main__":
    main()
