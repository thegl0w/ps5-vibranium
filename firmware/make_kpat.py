"""Pattern kernel stub (tier 1 of KERNEL-PATTERN-STUDY.md): the per-processor fix without any per-build table.

The firmware installs it only for a kernel the table stub does not know, after finding, in the loaded image itself:
the entry point (KiSystemStartup) with its 12 known bytes, the unused tail of POOLCODE, and the HAL's local-APIC pointer
through the code shape of its two accessors (each exactly once, both naming the same variable). See windows_kstub_install.inc.

The stub runs on every processor at KiSystemStartup (a 5-byte jmp replaces its first two instructions, 9 bytes):
  * the six core PerfCtl MSRs zeroed (Linux's watchdog counter is still armed on every processor);
  * AMD's extended-APIC IER0..7 opened through HalpLocalApic (they come up with almost every vector masked);
  * EFER bit 16 cleared when the firmware found it set (cfg byte, as the table stub's cfg_xofix = 1).
Same code as make_kstub.py's ap_fix, without the drawing. Writes firmware/windows_kpat.inc.
"""
import re, subprocess, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
LLVM = Path("/opt/homebrew/opt/llvm/bin")
ENTRY = bytes.fromhex("4883ec38" "4c897c2430" "4c8bfc")    # sub rsp,38h / mov [rsp+30h],r15 / mov r15,rsp
MOVED = 9                                                    # the first two instructions; none is RIP-relative

asm = """
    .intel_syntax noprefix
    .text
kp_start:
    pushfq
    push rax
    push rcx
    push rdx
    push rsi
    push r9
    mov ecx, 0xC0010200
    xor eax, eax
    xor edx, edx
    mov r9d, 6
1:  wrmsr
    add ecx, 2
    dec r9d
    jnz 1b
    mov ecx, 0x1B
    rdmsr
    test eax, 0x400
    jnz 2f
    mov rsi, qword ptr [rip + 0x7EADBEEF]
kp_apic_next:
    test rsi, rsi
    jz 2f
    mov eax, dword ptr [rsi + 0x30]
    bt eax, 31
    jnc 2f
    mov eax, dword ptr [rsi + 0x400]
    bt eax, 0
    jnc 2f
    mov eax, dword ptr [rsi + 0x410]
    bt eax, 0
    jnc 2f
""" + "".join(f"    mov dword ptr [rsi + {0x480 + 16 * n:#x}], 0xFFFFFFFF\n" for n in range(8)) + """
2:  cmp byte ptr [rip + kp_xofix], 0
    je 3f
    mov ecx, 0xC0000080
    rdmsr
    btr eax, 16
    jnc 3f
    wrmsr
3:  pop r9
    pop rsi
    pop rdx
    pop rcx
    pop rax
    popfq
kp_moved:
    .fill 9, 1, 0xCC
    .byte 0xE9
kp_jmp_rel:
    .long 0
kp_xofix:
    .byte 0
kp_end:
"""

with tempfile.TemporaryDirectory() as t:
    s, o = Path(t) / "kpat.s", Path(t) / "kpat.o"
    s.write_text(asm)
    subprocess.run([LLVM / "llvm-mc", "-triple=x86_64-unknown-linux-gnu", "-filetype=obj", s, "-o", o], check=True)
    sym = {}
    for line in subprocess.run([LLVM / "llvm-nm", "-n", o], capture_output=True, text=True, check=True).stdout.splitlines():
        v, _, name = line.split()
        sym[name] = int(v, 16)
    b = Path(t) / "kpat.bin"
    subprocess.run([LLVM / "llvm-objcopy", "-O", "binary", "--only-section=.text", o, b], check=True)
    dump = b.read_bytes()
    relocs = subprocess.run([LLVM / "llvm-readobj", "-r", o], capture_output=True, text=True, check=True).stdout
assert "R_X86_64" not in relocs, relocs                     # position-independent: no relocations
blob = dump[:sym["kp_end"]]
apic_disp = sym["kp_apic_next"] - 4
assert blob[apic_disp:apic_disp + 4] == (0x7EADBEEF).to_bytes(4, "little"), "APIC displacement not where expected"
assert blob[sym["kp_moved"]:sym["kp_moved"] + MOVED] == b"\xCC" * MOVED

h = ["// SPDX-License-Identifier: MIT",
     "// Generated by make_kpat.py: the pattern kernel stub (per-processor fix for kernels the table does not know).",
     f"#define KPAT_MOVED {MOVED}U                 // bytes of KiSystemStartup replaced by the jmp (two whole instructions)",
     f"#define KPAT_OFF_APIC_DISP {apic_disp:#x}U     // disp32 of mov rsi, [rip + HalpLocalApic]",
     f"#define KPAT_OFF_APIC_NEXT {sym['kp_apic_next']:#x}U     // the instruction after it (RIP base)",
     f"#define KPAT_OFF_MOVED {sym['kp_moved']:#x}U         // the displaced instructions are copied here",
     f"#define KPAT_OFF_JMP_REL {sym['kp_jmp_rel']:#x}U       // rel32 of the jmp back to KiSystemStartup + KPAT_MOVED",
     f"#define KPAT_OFF_XOFIX {sym['kp_xofix']:#x}U         // 1 = clear EFER bit 16",
     "STATIC CONST UINT8 mKpatEntry[12] = {" + ",".join(f"0x{b:02x}" for b in ENTRY) + "};",
     "STATIC CONST UINT8 mKpatBlob[] = {" + ",".join(f"0x{b:02x}" for b in blob) + "};"]
(HERE / "windows_kpat.inc").write_text("\n".join(h) + "\n")
print(f"pattern stub: {len(blob)} bytes; apic disp at {apic_disp:#x}, moved at {sym['kp_moved']:#x}, jmp rel at {sym['kp_jmp_rel']:#x}")
