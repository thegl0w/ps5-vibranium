"""Merge every firmware/windows_kstub*.inc (make_kstub.py output, one per ntoskrnl build) into one header with a
table, so a single firmware build serves every Windows kernel we have a stub for.

Proposed home: firmware/kstub_table.py. Usage:
  kstub_table.py header OUT.h     write the merged header (prepare.py writes it as WindowsKstub.h)
  kstub_table.py list             one line per build: "<TimeDateStamp> <SizeOfImage> <file>" (for run_stage.sh's check)
The per-build values (image identity, code/ext slack, HAL probe offset) and arrays (blob, ext, fingerprint,
hooks) are renamed per build; everything else (config/offset defines, the hook typedef) must be identical across
builds, which is checked here, because the install code uses them for every build.
"""
import os
import re
import sys
from pathlib import Path

FW = Path(os.environ.get("KSTUB_FWDIR") or Path(__file__).resolve().parent)
PER_BUILD = ["TIMESTAMP", "IMAGE_SIZE", "RVA", "SLACK", "EXT_RVA", "EXT_SLACK", "SCRATCH_RVA", "SCRATCH_LEN",
             "PROBE_RVA"]
ARRAYS = ["mKstubBlob", "mKstubExt", "mKstubPre", "mKstubHooks"]
DEF = re.compile(r"^#define KSTUB_([A-Z0-9_]+) (0x[0-9a-fA-F]+)U")


def parse(path):
    defs, body, typedef = {}, [], None
    for line in path.read_text().splitlines():
        m = DEF.match(line)
        if m:
            defs[m.group(1)] = int(m.group(2), 16)
        elif line.startswith("typedef struct") and "KSTUB_HOOK" in line:
            typedef = line
        else:
            body.append(line)
    missing = [k for k in PER_BUILD if k not in defs]
    if missing or typedef is None:
        sys.exit(f"{path.name}: missing {missing or 'KSTUB_HOOK typedef'}")
    return defs, body, typedef


def builds(fwdir=FW):
    out = []
    for inc in sorted(fwdir.glob("windows_kstub*.inc")):
        if inc.name == "windows_kstub_install.inc":
            continue
        defs, body, typedef = parse(inc)
        out.append((inc, defs, body, typedef))
    if not out:
        sys.exit("no windows_kstub*.inc files")
    seen = {}
    for inc, defs, *_ in out:
        key = (defs["TIMESTAMP"], defs["IMAGE_SIZE"])
        if key in seen:
            sys.exit(f"{inc.name} and {seen[key]} are for the same kernel")
        seen[key] = inc.name
    return out


def header(fwdir=FW):
    bs = builds(fwdir)
    shared0 = {k: v for k, v in bs[0][1].items() if k not in PER_BUILD}
    for inc, defs, _, typedef in bs[1:]:
        shared = {k: v for k, v in defs.items() if k not in PER_BUILD}
        if shared != shared0 or typedef != bs[0][3]:
            sys.exit(f"{inc.name}: shared layout differs from {bs[0][0].name}; regenerate both with one make_kstub.py")
    h = ["// Generated by kstub_table.py from " + ", ".join(b[0].name for b in bs) + ". Do not edit.",
         bs[0][3]]
    h += [f"#define KSTUB_{k} 0x{v:x}U" for k, v in sorted(shared0.items())]
    rows = []
    for inc, defs, body, _ in bs:
        tag = f"{defs['TIMESTAMP']:08x}"
        text = "\n".join(body)
        for a in ARRAYS:
            text = re.sub(rf"\b{a}\b", f"{a}_{tag}", text)
        h.append(f"// ---- {inc.name}")
        h.append(text.strip())
        rows.append("  { \"%s\", 0x%xU, 0x%xU, 0x%xU, 0x%xU, 0x%xU, 0x%xU, 0x%xU, 0x%xU, 0x%xU,\n"
                    "    mKstubPre_%s, mKstubBlob_%s, sizeof (mKstubBlob_%s), mKstubExt_%s, sizeof (mKstubExt_%s),\n"
                    "    mKstubHooks_%s, ARRAY_SIZE (mKstubHooks_%s) }," % (
                        (inc.name, *(defs[k] for k in PER_BUILD)) + (tag,) * 7))
    h.append("""typedef struct {
  CONST CHAR8 *Name;
  UINT32 Timestamp, ImageSize, Rva, Slack, ExtRva, ExtSlack, ScratchRva, ScratchLen, ProbeRva;
  CONST UINT64 *Pre;            // FNV-1a of the 16 bytes before the slack (2026-11-22: no kernel bytes stored)
  CONST UINT8 *Blob;
  UINTN BlobLen;
  CONST UINT8 *Ext;
  UINTN ExtLen;
  CONST KSTUB_HOOK *Hooks;
  UINTN HookCount;
} KSTUB_BUILD;""")
    h.append("STATIC CONST KSTUB_BUILD mKstubBuilds[] = {\n" + "\n".join(rows) + "\n};")
    return "\n".join(h) + "\n"


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "header":
        Path(sys.argv[2]).write_text(header())
    elif len(sys.argv) == 2 and sys.argv[1] == "list":
        for inc, defs, *_ in builds():
            print(f"0x{defs['TIMESTAMP']:08x} 0x{defs['IMAGE_SIZE']:x} {inc.name}")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
